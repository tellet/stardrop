"""Rewrites docs/THIRD-PARTY.md from `cargo metadata` on standard input.

Called by scripts/third-party.sh; not meant to be run on its own.
"""

import collections
import json
import sys

meta = json.load(sys.stdin)
crates = sorted(
    (p for p in meta["packages"] if p["name"] != "stardrop"),
    key=lambda p: p["name"].lower(),
)
counts = collections.Counter(p.get("license") or "not stated" for p in crates)

with open("docs/THIRD-PARTY.md", "w") as out:
    out.write("# Third-party crates\n\n")
    out.write("Every crate compiled into Stardrop, and the licence it is offered\n")
    out.write("under. Generated by `./scripts/third-party.sh`; do not edit by hand.\n\n")
    out.write(f"{len(crates)} crates.\n\n")
    out.write("| Licence | Crates |\n|---|---|\n")
    for licence, number in counts.most_common():
        out.write(f"| {licence} | {number} |\n")
    out.write("\n## Every crate\n\n| Crate | Version | Licence |\n|---|---|---|\n")
    for crate in crates:
        licence = crate.get("license") or "not stated"
        out.write(f"| {crate['name']} | {crate['version']} | {licence} |\n")

print(f"wrote docs/THIRD-PARTY.md ({len(crates)} crates)")
